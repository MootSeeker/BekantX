"""Board outline with rounded corners (layout rule 2026-11-19: "PCB-Ecken sinnvoll abrunden").

  "C:/Program Files/KiCad/10.0/bin/python.exe" tools/pcb/bekantx_outline.py <in.kicad_pcb> <out.kicad_pcb>

The outline comes from CAD/board_interface.json (generated by CAD/src/bekantx_enclosure.py): the polygon of the
rectangle with the USB tab, corner_radius for the four outer corners of the rectangle, tab_corner_radius for the
corners of the tab (the two inner ones are concave fillets, the milling radius). All Edge.Cuts drawings are
replaced by lines and arcs. The zones keep their square outlines; the fill is clipped at the board edge.
"""
import json, math, sys

import pcbnew

from bekantx_layout import MM, P, ROOT


def corners(iface):
    """[(vertex, radius)] in polygon order."""
    b = iface["board"]
    W, H = b["width"], b["depth"]
    R, r = b.get("corner_radius", 0.0), b.get("tab_corner_radius", 0.0)
    out = []
    for x, y in b["outline"]:
        outer = (x, y) in ((0.0, 0.0), (W, 0.0), (W, H), (0.0, H))
        out.append(((x, y), R if outer else r))
    return out


def main(src, dst):
    iface = json.loads((ROOT / "CAD" / "board_interface.json").read_text(encoding="utf-8"))
    board = pcbnew.LoadBoard(str(src))
    old = [d for d in board.GetDrawings() if d.GetLayer() == pcbnew.Edge_Cuts]
    cs = corners(iface)
    n = len(cs)
    ends = []                                  # (tangent point in, tangent point out) per vertex
    for i, (v, rad) in enumerate(cs):
        a, b = cs[i - 1][0], cs[(i + 1) % n][0]
        u = ((a[0] - v[0]) / math.dist(a, v), (a[1] - v[1]) / math.dist(a, v))
        w = ((b[0] - v[0]) / math.dist(b, v), (b[1] - v[1]) / math.dist(b, v))
        if rad <= 0:
            ends.append((v, v, None))
            continue
        t1 = (v[0] + u[0] * rad, v[1] + u[1] * rad)
        t2 = (v[0] + w[0] * rad, v[1] + w[1] * rad)
        c = (v[0] + (u[0] + w[0]) * rad, v[1] + (u[1] + w[1]) * rad)       # 90 degree corners only
        d = math.dist(v, c)
        mid = (c[0] + (v[0] - c[0]) / d * rad, c[1] + (v[1] - c[1]) / d * rad)
        ends.append((t1, t2, mid))
    for i, (t1, t2, mid) in enumerate(ends):
        if mid is not None:
            s = pcbnew.PCB_SHAPE(board)
            s.SetShape(pcbnew.SHAPE_T_ARC)
            s.SetArcGeometry(P(*t1), P(*mid), P(*t2))
            s.SetLayer(pcbnew.Edge_Cuts)
            s.SetWidth(MM(0.1))
            board.Add(s)
        nxt = ends[(i + 1) % n][0]
        if math.dist(t2, nxt) > 1e-6:
            s = pcbnew.PCB_SHAPE(board)
            s.SetShape(pcbnew.SHAPE_T_SEGMENT)
            s.SetStart(P(*t2))
            s.SetEnd(P(*nxt))
            s.SetLayer(pcbnew.Edge_Cuts)
            s.SetWidth(MM(0.1))
            board.Add(s)
    for d in old:                              # removals last: pcbnew proxies break after Remove()
        board.Remove(d)
    pcbnew.SaveBoard(str(dst), board)
    print(f"outline: {len(old)} edge drawings replaced, radii {sorted({r for _v, r in cs})} mm")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
